#!/usr/bin/env python3
"""
Fold-2 equal-weight decomposition + one-sample tests of P1 canonical against
the two passive benchmarks, under corrected costs. Eval-only deterministic
replays, no training, fold 4 never loaded. Writes
results/r2/corrected/ew_decomposition.md.

  * equal_weight_k5_band010 vs ew_matched_execution vs ew_matched_execution
    with smoothing removed (all else identical) -> isolates smoothing, and
    reports where its effect comes from (invested fraction, costs, turnover)
  * P1 canonical net return (n=20 seeds, hardening_results.csv) vs each EW
    point value: one-sample t (two- and one-sided), Wilcoxon signed-rank,
    sign test
"""
import copy
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

import run_baselines_corrected as B  # sets R2_DIR, installs the fold-4 guard

import numpy as np
import pandas as pd
from scipy import stats

import main as main_module
from config import ShieldType
from evaluation import WalkForwardEvaluator
from run_baselines import PriceHistory, build_strategies

P1_CSV = B.rc.R2_DIR / "hardening" / "hardening_results.csv"
OUT_PATH = B.rc.R2_DIR / "ew_decomposition.md"
STORED = B.OUT_CSV
NO_SMOOTH = "ew_matched_minus_smoothing"


def episode(env, strategy, rf):
    obs, info = env.reset()
    navs, costs, turns, invested, done = [env.portfolio.initial_capital], [], [], [], False
    while not done:
        obs, _, term, trunc, info = env.step(strategy.get_action(obs, info))
        done = term or trunc
        navs.append(info.get('nav', navs[-1]))
        costs.append(info.get('transaction_cost', 0.0))
        turns.append(info.get('turnover', 0.0))
        invested.append(float(np.sum(info['portfolio_state'].weights)))
    nav = np.asarray(navs)
    return {'return': B.compute_return_metrics(navs, risk_free_rate=rf)['return'],
            'turnover': float(np.mean(turns)), 'txn_cost_nav': float(np.sum(np.array(costs) / nav[:-1])),
            'invested_mean': float(np.mean(invested)), 'invested_d0_40': float(np.mean(invested[:40])),
            'invested_d40_plus': float(np.mean(invested[40:]))}


def replay_fold2():
    windows = main_module.PAPER_WALK_FORWARD_WINDOWS
    dates = [d for w in windows for d in (*w['train'], *w['test'])]
    base = main_module.create_experiment_config(
        tickers=B.TICKERS, start_date=main_module._buffered_start_date(min(dates)), end_date=max(dates),
        total_timesteps=1, use_synthetic=False, seed=1)
    base.shield.shield_type = ShieldType.NONE
    features, prices_df, _, _, aligned = main_module.load_and_prepare_data(base, use_synthetic=False)
    B.rc.assert_no_fold4(aligned.index)
    prices = {t: prices_df[t].values for t in B.TICKERS}
    sp = WalkForwardEvaluator(base).generate_calendar_splits(aligned.index, windows)[1]
    (tr0, tr1), (te0, te1) = sp['train'], sp['test']
    cfg = copy.deepcopy(base)
    cfg.regime.calibrated_vol_thresholds = None
    main_module.calibrate_regime(cfg, aligned.iloc[tr0:tr1])     # audit defect #9
    tf, ta = features.iloc[te0:te1], aligned.iloc[te0:te1]
    tp = {t: p[te0:te1] for t, p in prices.items()}
    lb0 = max(0, te0 - B.LOOKBACK_DAYS)
    ph = PriceHistory({t: p[lb0:te1] for t, p in prices.items()}, lookback_len=te0 - lb0, tickers=B.TICKERS)
    rf = cfg.evaluation.risk_free_rate

    def env(c):
        return main_module.create_trading_env(tf, tp, c, aligned_data=ta, mode="test")

    k5 = build_strategies(len(B.TICKERS), cfg, ph, aligned.iloc[tr0:tr1])['equal_weight_k5_band010']
    rows = {'equal_weight_k5_band010': episode(env(copy.deepcopy(cfg)), k5, rf)}
    for name, ov in [(B.EW_MATCHED, B.EXEC_OVERRIDES),
                     (NO_SMOOTH, {**B.EXEC_OVERRIDES, 'environment.action_smoothing_beta': None})]:
        rows[name] = episode(env(B._apply_overrides(copy.deepcopy(cfg), ov)), B.ConstantEW(len(B.TICKERS)), rf)
    return rows


def main():
    rows = replay_fold2()
    stored = pd.read_csv(STORED).query("fold == 2").set_index('strategy')['return']
    for name in ('equal_weight_k5_band010', B.EW_MATCHED):
        assert abs(rows[name]['return'] - stored[name]) < 1e-9, (name, rows[name]['return'], stored[name])

    p1 = pd.read_csv(P1_CSV)
    can = p1[p1.arm == 'canonical']
    assert len(can) == 20 and can.seed.nunique() == 20
    x = can['return'].to_numpy()
    lo, hi = stats.ttest_1samp(x, 0.0).confidence_interval(0.95)

    L = ["# Fold-2 equal-weight decomposition and canonical-vs-passive tests -- corrected costs", "",
         "> Eval-only deterministic replays on the fold-2 test window (2015-2017); no training, fold 4 never "
         "loaded. Generated by `analyze_ew_decomposition.py`. Both EW replays reproduce the stored values in "
         "`baselines_corrected.csv` exactly (asserted).", "",
         "## 1. What differs between the two EW benchmarks", "",
         "| | equal_weight_k5_band010 | ew_matched_execution |", "|---|---|---|",
         "| target | 1/N | 1/N (constant action) |",
         "| decision cadence | 5 days (strategy-side) | 5 days (env `decision_frequency_days`) |",
         "| no-trade band | per asset, 0.10 vs actual drifted weight (strategy-side) | per asset, 0.10 vs actual "
         "drifted weight (env `no_trade_band`; same rule) |",
         "| gross cap 2.0 | n/a | applied; never binds for a 1/N long book |",
         f"| action smoothing | none | beta {B.EXEC_OVERRIDES['environment.action_smoothing_beta']}: "
         "w_t = 0.9 w_(t-1) + 0.1 a_t from flat |", "",
         "Smoothing is the only material difference (the cadence phase differs by one step: strategy decides on "
         "steps 0, 4, 9, ...; env on 0, 5, 10, ...). The third row below removes only smoothing from the matched "
         "execution.", "",
         "| fold 2 | net return | turnover/day | cost/NAV | mean invested | invested d0-40 | invested d40+ |",
         "|---|---:|---:|---:|---:|---:|---:|"]
    for name, r in rows.items():
        L.append(f"| {name} | {r['return']:+.4f} | {r['turnover']:.4f} | {r['txn_cost_nav']:.4f} | "
                 f"{r['invested_mean']:.3f} | {r['invested_d0_40']:.3f} | {r['invested_d40_plus']:.3f} |")
    gap = rows['equal_weight_k5_band010']['return'] - rows[B.EW_MATCHED]['return']
    L += ["", f"Removing smoothing reproduces k5_band010 exactly, so the {gap * 100:.1f}-point gap is entirely "
          "smoothing. It is not a cost drag (the smoothed book has lower cost and turnover): it is an "
          "under-investment drag. From flat, the smoothed target 0.2(1-0.9^k) first clears the 0.10 band after "
          "~7 decisions (~35 trading days), and afterwards the residual gap to 1/N rarely exceeds the band, so "
          f"the book stays ~{rows[B.EW_MATCHED]['invested_d40_plus'] * 100:.0f}% invested -- a cash drag in a "
          "rising window.", "",
          "## 2. P1 canonical (n=20 seeds) vs each EW point value", "",
          f"Canonical net return: mean {x.mean():+.4f}, SD {x.std(ddof=1):.4f}, median {np.median(x):+.4f}, "
          f"95% t-CI of mean [{lo:+.4f}, {hi:+.4f}].", "",
          "| benchmark | value | mean diff | t(19) | t p (2-sided) | t p (1-sided, >) | Wilcoxon p (2-sided) | "
          "Wilcoxon p (1-sided) | seeds above | sign test p (2-sided) |",
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for name in ('equal_weight_k5_band010', B.EW_MATCHED):
        mu = rows[name]['return']
        t = stats.ttest_1samp(x, mu)
        above = int((x > mu).sum())
        L.append(f"| {name} | {mu:+.4f} | {x.mean() - mu:+.4f} | {t.statistic:.3f} | {t.pvalue:.4f} | "
                 f"{stats.ttest_1samp(x, mu, alternative='greater').pvalue:.4f} | {stats.wilcoxon(x - mu).pvalue:.4f} | "
                 f"{stats.wilcoxon(x - mu, alternative='greater').pvalue:.4f} | {above}/20 | "
                 f"{stats.binomtest(above, 20).pvalue:.4f} |")
    L += ["", "Caveats: each EW value is a single deterministic point on one test window, treated as known, so "
          "these tests capture seed-to-seed training variance only, not market-path uncertainty. They are not "
          "part of the 8-test Holm family in `oracle_anomaly.md` and were not pre-specified. Supported claim: "
          "across training seeds, corrected canonical beats ew_matched_execution on fold 2 (t and Wilcoxon p < 0.01, sign test p = 0.012); "
          "its margin over equal_weight_k5_band010 is borderline (two-sided t misses 0.05; rank and sign tests "
          "pass). Canonical still trails P1 untrained on the same window (see `p1_stats_interim.md`).", ""]
    OUT_PATH.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    print(f"wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
